--ALTER VIEW .DBO.Q_COMPLEX_CARE_MERCY_BEACN_BENCHMARKS AS
SELECT CBENCH.ID, 
	CBENCH.DOCSERNO, 
	CAST(CBENCH.VISITDT AS DATE) AS [VISIT_DATE], 
	CBENCH.VISITTM, 
	CBENCH.USERID, 
	CBENCH.PARENTDOCSERNO, 
	CBENCH.CLIENTNUMBER AS [CLIENT_NUMBER], 
	CAST(CBENCH.PATHWAY_DATE AS DATE) AS [PATHWAY_DATE], 
	CAST(CBENCH.ADDED_COHORT_DATE AS DATE) AS [ADDED_COHORT_DATE], 
	CAST(CBENCH.FIRST_POST_REFERRAL_CONTACT_DATE AS DATE) AS [FIRST_POST_REFERRAL_CONTACT_DATE], 
	CAST(CBENCH.ENROLLMENT_DATE AS DATE) AS [ENROLLMENT_DATE], 
	CAST(CBENCH.FIRST_POST_ENROLLMENT_CONTACT_DATE AS DATE) AS [FIRST_POST_ENROLLMENT_CONTACT_DATE], 
	CAST(CBENCH.COMPLETE_ADMISSION_SERVICE_DATE AS DATE) AS [COMPLETE_ADMISSION_SERVICE_DATE], 
	CAST(CBENCH.PSYCH_EVAL_DATE AS DATE) AS [PSYCH_EVAL_DATE], 
	CAST(CBENCH.TREATMENT_TEAM_ASSIGNMENT_DATE AS DATE) AS [TREATMENT_TEAM_ASSIGNMENT_DATE], 
	CBENCH.TIEDENROLLMENT
FROM BEHAVHEALT_LIVE.DBO.PWMERCYBEACNBENCHMARKS AS [CBENCH]
WHERE CBENCH.DOCREVNO = ' 0 ';