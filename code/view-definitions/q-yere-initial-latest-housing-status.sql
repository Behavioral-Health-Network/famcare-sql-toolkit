--ALTER VIEW DBO.Q_YERE_INITIAL_LATEST_HOUSING_STATUS AS
WITH [ALL_HOUSING] AS (
    SELECT
        EH.CLIENT_NUMBER,
        EH.TIEDENROLLMENT,
        EH.DOCSERNO,
        EH.PARENT_DOCSERNO,
		EH.VISIT_DATE,
        EH.VISIT_TIME,
        EH.USERID,
		EH.FORM_TYPE,
        EH.HOUSING_START_DATE,
        EH.HOUSING_END_DATE,
        EH.CLIENT_HOUSING_STATUS,
        EH.HOUSING_STATUS_INCARCERATED,
        EH.UNHOUSED_SHELTER,
        EH.IF_UNHOUSED_EXP,
        EH.WORRIED_LOSING_HOUSING,
        EH.HOMELESS_HOUSING_INSECURE_ETO
    FROM DBO.Q_YERE_ALL_HOUSING_STATUS AS [EH]
),

[INITIAL_HOUSING] AS (
    SELECT
        CLIENT_NUMBER,
        TIEDENROLLMENT,
        DOCSERNO AS [INITIAL_DOCSERNO],
        PARENT_DOCSERNO AS [INITIAL_PARENT_DOCSERNO],
		FORM_TYPE AS [INITIAL_PARENT_FORM_TYPE],
        CAST(HOUSING_START_DATE AS DATE) AS [INITIAL_HOUSING_START_DATE],
        CAST(HOUSING_END_DATE AS DATE) AS [INITIAL_HOUSING_END_DATE],
        CLIENT_HOUSING_STATUS AS [INITIAL_HOUSING_STATUS_DESCRIPTION],
        CAST(VISIT_DATE AS DATE) AS [INITIAL_VISIT_DATE],
        VISIT_TIME AS [INITIAL_VISIT_TIME],
        USERID AS [INITIAL_USERID]
    FROM (
        SELECT
            AH.*,
            ROW_NUMBER() OVER (
                PARTITION BY TIEDENROLLMENT
                ORDER BY HOUSING_START_DATE ASC, DOCSERNO ASC
            ) AS [RN]
        FROM ALL_HOUSING AS [AH]
    ) AS [X]
    WHERE RN = 1
),

[LATEST_HOUSING] AS (
    SELECT
        CLIENT_NUMBER,
        TIEDENROLLMENT,
        DOCSERNO AS [LATEST_DOCSERNO],
        PARENT_DOCSERNO AS [LATEST_PARENT_DOCSERNO],
		FORM_TYPE AS [LATEST_PARENT_FORM_TYPE],
        CAST(HOUSING_START_DATE AS DATE) AS [LATEST_HOUSING_START_DATE],
        CAST(HOUSING_END_DATE AS DATE) AS [LATEST_HOUSING_END_DATE],
        CLIENT_HOUSING_STATUS AS [LATEST_HOUSING_STATUS_DESCRIPTION],
        CAST(VISIT_DATE AS DATE) AS [LATEST_VISIT_DATE],
        VISIT_TIME AS [LATEST_VISIT_TIME],
        USERID AS [LATEST_USERID]
    FROM (
        SELECT
            AH.*,
            ROW_NUMBER() OVER (
                PARTITION BY TIEDENROLLMENT
                ORDER BY HOUSING_START_DATE DESC, DOCSERNO DESC
            ) AS [RN]
        FROM ALL_HOUSING AS [AH]
    ) AS [X]
    WHERE RN = 1
)

SELECT
    L.CLIENT_NUMBER,
    L.TIEDENROLLMENT,

    -- Initial housing status
	I.INITIAL_DOCSERNO,
	I.INITIAL_PARENT_DOCSERNO,
	I.INITIAL_PARENT_FORM_TYPE,
    I.INITIAL_HOUSING_START_DATE,
    I.INITIAL_HOUSING_END_DATE,
    I.INITIAL_HOUSING_STATUS_DESCRIPTION,
    I.INITIAL_VISIT_DATE,
    I.INITIAL_VISIT_TIME,
    I.INITIAL_USERID,

    -- Latest housing status
    L.LATEST_DOCSERNO,
	L.LATEST_PARENT_DOCSERNO,
	L.LATEST_PARENT_FORM_TYPE,
    L.LATEST_HOUSING_START_DATE,
    L.LATEST_HOUSING_END_DATE,
    L.LATEST_HOUSING_STATUS_DESCRIPTION,
    L.LATEST_VISIT_DATE,
    L.LATEST_VISIT_TIME,
    L.LATEST_USERID,

	-- Status change flag
    CASE
        WHEN I.INITIAL_HOUSING_STATUS_DESCRIPTION = L.LATEST_HOUSING_STATUS_DESCRIPTION
        THEN 0
        ELSE 1
    END AS [STATUS_CHANGED_FLAG]

FROM LATEST_HOUSING AS [L]
LEFT JOIN INITIAL_HOUSING AS [I]
    ON I.TIEDENROLLMENT = L.TIEDENROLLMENT
INNER JOIN DBO.Q_CLIENT_BHN AS [C]
    ON C.CLIENT_NUMBER = L.CLIENT_NUMBER;
