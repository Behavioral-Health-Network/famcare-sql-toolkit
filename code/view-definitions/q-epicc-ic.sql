LEFT JOIN EPICC_PROGRAM_PARTICIPATION AS [EPP]
	ON EIC.PROGRAM_PARTICIPATION_IC = EPP.CODE
INNER JOIN Q_CLIENT_BHN AS [C]
	ON EIC.CLIENTNUMBER = C.CLIENT_NUMBER
LEFT JOIN COMMUNITY_REFERRAL_SOURCE AS [CRS]
	ON EIC.COMMUNITY_REFERRAL_SOURCE_IC = CRS.CODE
LEFT JOIN EPICC_TYPES_MAT AS [CURRENT_MAT]
	ON EIC.CURRENT_SCRIPT_MAT_TYPE = CURRENT_MAT.CODE
LEFT JOIN EPICC_TYPES_MAT AS [HOSPITAL_MAT]
	ON EIC.WHAT_MAT_INITIATED_HOSPITAL = HOSPITAL_MAT.CODE
LEFT JOIN EPICC_TYPES_MAT AS [DISCHARGE_MAT]
	ON EIC.WHAT_MAT_SCRIPT_DISCHARGE = DISCHARGE_MAT.CODE
WHERE EIC.DOCREVNO = ' 0 ';