	HEARD_ABOUT_FROM_FLYER,
	HEARD_ABOUT_FROM_CHURCH,
	HEARD_ABOUT_FROM_OTHER,
	PROGRAM_PARTICIPATION_IC AS [EPICC_PROGRAM_PARTICIPATION_IC_CODE],
	EPP.DESCRIPTION AS [EPICC_PROGRAM_PARTICIPATION_IC_DESCRIPTION],
	TREATMENT_PATH_IC,
	TREATMENT_PATH_IC_UNKNOWN,
	WHO_INITIATED_REFERRAL,
	COMMUNITY_REFERRAL_SOURCE_IC AS [COMMUNITY_REFERRAL_SOURCE_IC_CODE],
	CRS.DESCRIPTION AS [COMMUNITY_REFERRAL_SOURCE_IC_DESCRIPTION],
	TYPE_CONTACT_IC,
	REASON_IC_NOT_SUCCESS,
	CONSENT_CRC_REFERRAL_IC,
	REASON_CONSENT_REFUSED_CRC_IC,
	EPICC_OPIOIDS_OF_USE,
	OPIOID_OF_USE_FENTANYL,
	OPIOID_OF_USE_HEROIN,
	OPIOID_OF_USE_PRESCRIPTION_OPIATES,
	OPIOID_OF_USE_SUBOXONE_MAT,
	OPIOID_OF_USE_OTHER,
	OPIOID_OF_USE_NA,
	OTHER_OPIOID_IC,
	OVERDOSE_EVENT_REFERRAL,
	OVERDOSE_EVENT_REFERRAL_UNKNOWN,
	OVERDOSE_LOCATION,
	SPECIFY_OTHER_LOCATION,
	FIRST_OVERDOSE,
	MOST_RECENT_PAST_OVERDOSE_DATE,
	MOST_RECENT_PAST_OVERDOSE_DATE_UNKNOWN,
	NUM_PAST_OVERDOSES,
	SU_TREATMENT_PAST_TWELVE_MOS,
