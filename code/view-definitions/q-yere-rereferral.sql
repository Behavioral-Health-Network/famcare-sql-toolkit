--ALTER VIEW dbo.Q_YERE_REREFERRAL AS
WITH [YERE_EVENTS] AS (
	SELECT
		A.CLIENT_NUMBER,
		A.CLIENT_LAST,
		A.CLIENT_FIRST,
		A.PROGRAM_WORKER_EMPLOYEE_NUMBER,
		A.PROGRAM_WORKER_LAST,
		A.PROGRAM_WORKER_FIRST,
		A.ENROLLMENT_STARTING_DATE,
		A.ENROLLMENT_ENDING_DATE,
		A.PP_DOCSERNO,
		A.PC_DOCSERNO,
		A.PEC_PATHCLIENT_DOCSERNO,
		A.PATHWAY_ID,
		A.PWY_EVENT,
		A.PE_DATE_ACCOMPLISHED AS [REFERRAL_EVENT_DATE]
	FROM DBO.Q_BHNWIDE_PATHCLIENT_ENROLLMENTS AS [A]
	WHERE
		A.PATHWAY_ID = '55320240807125033701'
		AND A.PWY_EVENT = 'YERE Referral'
),

[YERE_REF_WITH_FORM] AS (
	SELECT
		E.*,
		R.YERE_REFERRING_HOSPITAL,
		R.YERE_REFERRING_HOSPITAL_DESCRIPTION,
		R.PRIMARY_REASON_REFERRAL,
		R.REFERRED_FROM,
		R.DOCSERNO AS [REFERRAL_FORM_DOCSERNO],
		R.PATHWAY_DATE
	FROM YERE_EVENTS AS [E]
	LEFT JOIN DBO.Q_YERE_REFERRAL AS [R]
		ON R.CLIENT_NUMBER = E.CLIENT_NUMBER
		AND R.TIEDENROLLMENT  = E.PC_DOCSERNO
		AND R.EVENT_NAME = E.PWY_EVENT
),

[BHN_REF] AS (
	SELECT
		CLIENT_NUMBER,
		COUNT(*) AS [TOTAL_BHN_REFERRALS],
		MAX(ENROLLMENT_STARTING_DATE) AS [LAST_BHN_REFERRAL_DATE]
	FROM DBO.Q_PROVIDERPLACEMENT_BHN
	GROUP BY CLIENT_NUMBER
),

[FINAL_WITH_RN] AS (
	SELECT
		F.CLIENT_NUMBER,
		F.CLIENT_LAST,
		F.CLIENT_FIRST,
		F.ENROLLMENT_STARTING_DATE AS [LATEST_ENROLLMENT_STARTING_DATE],
		F.ENROLLMENT_ENDING_DATE AS [LATEST_ENROLLMENT_ENDING_DATE],
		F.YERE_REFERRING_HOSPITAL_DESCRIPTION AS [LATEST_REFERRING_HOSPITAL],
		F.REFERRED_FROM AS [LATEST_PATIENT_LOCATION],
		F.PRIMARY_REASON_REFERRAL AS [LATEST_REFERRAL_REASON],
		F.PROGRAM_WORKER_LAST,
		F.PROGRAM_WORKER_FIRST,
		F.REFERRAL_FORM_DOCSERNO AS [LATEST_REFERRAL_FORM_DOCSERNO],

		-- Client-level YERE referral metrics
		COUNT(*) OVER (PARTITION BY F.CLIENT_NUMBER) AS [TOTAL_YERE_REFERRALS],
		MAX(F.ENROLLMENT_STARTING_DATE) OVER (PARTITION BY F.CLIENT_NUMBER) AS [LAST_YERE_REFERRAL_DATE],

		-- Agency-wide referral metrics
		AR.TOTAL_BHN_REFERRALS,
		AR.LAST_BHN_REFERRAL_DATE,

		-- Window function to pick the latest referral per client
		ROW_NUMBER() OVER (
			PARTITION BY F.CLIENT_NUMBER
			ORDER BY F.ENROLLMENT_STARTING_DATE DESC
		) AS [RN]

	FROM YERE_REF_WITH_FORM AS [F]
	LEFT JOIN BHN_REF AS [AR]
		ON AR.CLIENT_NUMBER = F.CLIENT_NUMBER
)

SELECT RN.CLIENT_NUMBER,
	RN.CLIENT_LAST,
	RN.CLIENT_FIRST,
	RN.LATEST_REFERRING_HOSPITAL,
	RN.LATEST_REFERRAL_REASON,
	RN.LATEST_REFERRAL_FORM_DOCSERNO,
	RN.TOTAL_YERE_REFERRALS,
	RN.LAST_YERE_REFERRAL_DATE,
	RN.TOTAL_BHN_REFERRALS,
	RN.LAST_BHN_REFERRAL_DATE
FROM FINAL_WITH_RN AS [RN]
WHERE RN.RN = 1;