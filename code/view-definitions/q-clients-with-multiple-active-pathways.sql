-- ALTER VIEW DBO.Q_CLIENTS_WITH_MULTIPLE_ACTIVE_PATHWAYS AS
WITH PathwayCounts AS (
	SELECT C.CLIENT_NAME,
		C.CLIENT_NUMBER,
		PC.USERID AS [WHODUNIT],
		PP.DOCSERNO AS [PP DOCSERNO],
		PP.REGION AS [PROGRAM_CODE],
		P.PROVIDERNAME AS [PROGRAM_DESCRIPTION],
		PP.PRIMARYPROVIDERCODE AS [AGENCY_CODE],
		PP.THEPROVIDERNAME AS [AGENCY_DESCRIPTION],
		PWY.PATHWAYNAME,
		COUNT(C.CLIENT_NUMBER) OVER (PARTITION BY C.CLIENT_NUMBER) AS [COUNT_PATHWAY]
	FROM DBO.PATHWAY AS [PWY]
	INNER JOIN DBO.PATHWAYCLIENT AS [PC] 
		ON PC.PARENTDOCSERNO = PWY.DOCSERNO
		AND PC.DOCREVNO = ' 0 '
	INNER JOIN DBO.Q_PROVIDERPLACEMENT AS [PP] 
		ON PC.DOCSERNO = PP.DOCSERNO
	LEFT JOIN DBO.Q_PROVIDER AS [P] 
		ON PP.REGION = P.PROVIDERCODE
	INNER JOIN DBO.Q_CLIENT_BHN AS [C] 
		ON PC.CLIENTNUMBER = C.CLIENT_NUMBER
	INNER JOIN DBO.PATHWAY AS [PWY2] 
		ON PWY.ID = PWY2.ID
		AND PWY2.DOCREVNO = ' 0 '
	WHERE PWY.DOCREVNO = ' 0 '
		AND PC.ENDDATE IS NULL
		)
SELECT *
FROM PathwayCounts
WHERE [COUNT_PATHWAY] > 1;