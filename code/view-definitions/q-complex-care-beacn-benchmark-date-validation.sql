USE BEHAVHEALT_LIVE;
GO

--ALTER VIEW dbo.Q_COMPLEX_CARE_BEACN_BENCH_DATE_VALIDATION AS
SELECT
	B.CLIENT_NUMBER,
	C.CLIENT_LAST,
	C.CLIENT_FIRST,
	B.DOCSERNO,
	B.ADDED_COHORT_DATE,
	B.FIRST_POST_REFERRAL_CONTACT_DATE AS [FIRST_POST_SELECTION_CONTACT_DATE],
	B.ENROLLMENT_DATE,
	B.FIRST_POST_ENROLLMENT_CONTACT_DATE,
	B.COMPLETE_ADMISSION_SERVICE_DATE,
	B.PSYCH_EVAL_DATE,
	B.TREATMENT_TEAM_ASSIGNMENT_DATE,
	X.EX_ADDED_COHORT_DATE,
	X.EX_REFERRAL_CONTACT,
	X.EX_ENROLLMENT_DATE,
	X.EX_POST_ENROLLMENT_CONTACT,
	X.EX_ADMISSION_SERVICE,
	X.EX_PSYCH_EVAL,
	X.EX_TEAM_ASSIGNMENT,
	X.EXCEPTION_SUMMARY
FROM Q_COMPLEX_CARE_MERCY_BEACN_BENCHMARKS AS [B]
INNER JOIN Q_CLIENT_BHN AS [C]
	ON C.CLIENT_NUMBER = B.CLIENT_NUMBER
CROSS APPLY (
	SELECT
		/* ============================================
		   REQUIRED FIELDS
		   ============================================ */

		CASE 
			WHEN B.ADDED_COHORT_DATE IS NULL 
				THEN 'ADDED_COHORT_DATE is NULL'
			ELSE 'OK'
		END AS EX_ADDED_COHORT_DATE,

		CASE 
			WHEN B.FIRST_POST_REFERRAL_CONTACT_DATE IS NULL 
				THEN 'FIRST_POST_SELECTION_CONTACT_DATE is NULL'
			WHEN B.FIRST_POST_REFERRAL_CONTACT_DATE < B.ADDED_COHORT_DATE 
				THEN 'FIRST_POST_SELECTION_CONTACT_DATE precedes ADDED_COHORT_DATE'
			ELSE 'OK'
		END AS EX_REFERRAL_CONTACT,

		/* ============================================
		   CONDITIONAL ENROLLMENT REQUIREMENT
		   ============================================ */

		CASE 
			WHEN (
					B.FIRST_POST_ENROLLMENT_CONTACT_DATE IS NOT NULL
				 OR B.COMPLETE_ADMISSION_SERVICE_DATE IS NOT NULL
				 OR B.PSYCH_EVAL_DATE IS NOT NULL
				 OR B.TREATMENT_TEAM_ASSIGNMENT_DATE IS NOT NULL
				 )
				 AND B.ENROLLMENT_DATE IS NULL
				THEN 'ENROLLMENT_DATE required but NULL'

			WHEN B.ENROLLMENT_DATE IS NOT NULL
				 AND B.ENROLLMENT_DATE < B.ADDED_COHORT_DATE
				THEN 'ENROLLMENT_DATE precedes ADDED_COHORT_DATE'

			ELSE 'OK'
		END AS EX_ENROLLMENT_DATE,

		/* ============================================
		   POST-ENROLLMENT FIELDS
		   NULL = allowed
		   ============================================ */

		CASE 
			WHEN B.FIRST_POST_ENROLLMENT_CONTACT_DATE IS NULL THEN 'NULL'
			WHEN B.ENROLLMENT_DATE IS NULL 
				THEN 'FIRST_POST_ENROLLMENT_CONTACT_DATE exists but ENROLLMENT_DATE is NULL'
			WHEN B.FIRST_POST_ENROLLMENT_CONTACT_DATE < B.ENROLLMENT_DATE 
				THEN 'FIRST_POST_ENROLLMENT_CONTACT_DATE precedes ENROLLMENT_DATE'
			ELSE 'OK'
		END AS EX_POST_ENROLLMENT_CONTACT,

		CASE 
			WHEN B.COMPLETE_ADMISSION_SERVICE_DATE IS NULL THEN 'NULL'
			WHEN B.ENROLLMENT_DATE IS NULL 
				THEN 'COMPLETE_ADMISSION_SERVICE_DATE exists but ENROLLMENT_DATE is NULL'
			WHEN B.COMPLETE_ADMISSION_SERVICE_DATE < B.ENROLLMENT_DATE 
				THEN 'COMPLETE_ADMISSION_SERVICE_DATE precedes ENROLLMENT_DATE'
			ELSE 'OK'
		END AS EX_ADMISSION_SERVICE,

		CASE 
			WHEN B.PSYCH_EVAL_DATE IS NULL THEN 'NULL'
			WHEN B.ENROLLMENT_DATE IS NULL 
				THEN 'PSYCH_EVAL_DATE exists but ENROLLMENT_DATE is NULL'
			WHEN B.PSYCH_EVAL_DATE < B.ENROLLMENT_DATE 
				THEN 'PSYCH_EVAL_DATE precedes ENROLLMENT_DATE'
			ELSE 'OK'
		END AS EX_PSYCH_EVAL,

		CASE 
			WHEN B.TREATMENT_TEAM_ASSIGNMENT_DATE IS NULL THEN 'NULL'
			WHEN B.ENROLLMENT_DATE IS NULL 
				THEN 'TREATMENT_TEAM_ASSIGNMENT_DATE exists but ENROLLMENT_DATE is NULL'
			WHEN B.TREATMENT_TEAM_ASSIGNMENT_DATE < B.ENROLLMENT_DATE 
				THEN 'TREATMENT_TEAM_ASSIGNMENT_DATE precedes ENROLLMENT_DATE'
			ELSE 'OK'
		END AS EX_TEAM_ASSIGNMENT,

		/* ============================================
		   EXCEPTION SUMMARY
		   ============================================ */

		(
			STUFF((
				SELECT '; ' + E
				FROM (
					VALUES
						(CASE WHEN B.ADDED_COHORT_DATE IS NULL 
								THEN 'ADDED_COHORT_DATE is NULL' END),

						(CASE WHEN B.FIRST_POST_REFERRAL_CONTACT_DATE IS NULL 
								THEN 'FIRST_POST_SELECTION_CONTACT_DATE is NULL'
							  WHEN B.FIRST_POST_REFERRAL_CONTACT_DATE < B.ADDED_COHORT_DATE 
								THEN 'FIRST_POST_SELECTION_CONTACT_DATE precedes ADDED_COHORT_DATE' END),

						(CASE WHEN (
										B.FIRST_POST_ENROLLMENT_CONTACT_DATE IS NOT NULL
									 OR B.COMPLETE_ADMISSION_SERVICE_DATE IS NOT NULL
									 OR B.PSYCH_EVAL_DATE IS NOT NULL
									 OR B.TREATMENT_TEAM_ASSIGNMENT_DATE IS NOT NULL
									 )
									 AND B.ENROLLMENT_DATE IS NULL
								THEN 'ENROLLMENT_DATE required but NULL'
							  WHEN B.ENROLLMENT_DATE IS NOT NULL
									 AND B.ENROLLMENT_DATE < B.ADDED_COHORT_DATE
								THEN 'ENROLLMENT_DATE precedes ADDED_COHORT_DATE' END),

						(CASE WHEN B.FIRST_POST_ENROLLMENT_CONTACT_DATE IS NOT NULL
								AND B.ENROLLMENT_DATE IS NULL
								THEN 'FIRST_POST_ENROLLMENT_CONTACT_DATE exists but ENROLLMENT_DATE is NULL'
							  WHEN B.FIRST_POST_ENROLLMENT_CONTACT_DATE IS NOT NULL
								AND B.FIRST_POST_ENROLLMENT_CONTACT_DATE < B.ENROLLMENT_DATE
								THEN 'FIRST_POST_ENROLLMENT_CONTACT_DATE precedes ENROLLMENT_DATE' END),

						(CASE WHEN B.COMPLETE_ADMISSION_SERVICE_DATE IS NOT NULL
								AND B.ENROLLMENT_DATE IS NULL
								THEN 'COMPLETE_ADMISSION_SERVICE_DATE exists but ENROLLMENT_DATE is NULL'
							  WHEN B.COMPLETE_ADMISSION_SERVICE_DATE IS NOT NULL
								AND B.COMPLETE_ADMISSION_SERVICE_DATE < B.ENROLLMENT_DATE
								THEN 'COMPLETE_ADMISSION_SERVICE_DATE precedes ENROLLMENT_DATE' END),

						(CASE WHEN B.PSYCH_EVAL_DATE IS NOT NULL
								AND B.ENROLLMENT_DATE IS NULL
								THEN 'PSYCH_EVAL_DATE exists but ENROLLMENT_DATE is NULL'
							  WHEN B.PSYCH_EVAL_DATE IS NOT NULL
								AND B.PSYCH_EVAL_DATE < B.ENROLLMENT_DATE
								THEN 'PSYCH_EVAL_DATE precedes ENROLLMENT_DATE' END),

						(CASE WHEN B.TREATMENT_TEAM_ASSIGNMENT_DATE IS NOT NULL
								AND B.ENROLLMENT_DATE IS NULL
								THEN 'TREATMENT_TEAM_ASSIGNMENT_DATE exists but ENROLLMENT_DATE is NULL'
							  WHEN B.TREATMENT_TEAM_ASSIGNMENT_DATE IS NOT NULL
								AND B.TREATMENT_TEAM_ASSIGNMENT_DATE < B.ENROLLMENT_DATE
								THEN 'TREATMENT_TEAM_ASSIGNMENT_DATE precedes ENROLLMENT_DATE' END)
				) AS ERR(E)
				WHERE E IS NOT NULL
				FOR XML PATH(''), TYPE
			).value('.', 'nvarchar(max)'), 1, 2, '')
		) AS EXCEPTION_SUMMARY
) AS X

/* ============================================
   FILTER: ONLY TRUE EXCEPTIONS
   ============================================ */
WHERE
	   X.EX_ADDED_COHORT_DATE <> 'OK'
	OR X.EX_REFERRAL_CONTACT <> 'OK'
	OR X.EX_ENROLLMENT_DATE <> 'OK'
	OR X.EX_POST_ENROLLMENT_CONTACT NOT IN ('OK','NULL')
	OR X.EX_ADMISSION_SERVICE NOT IN ('OK','NULL')
	OR X.EX_PSYCH_EVAL NOT IN ('OK','NULL')
	OR X.EX_TEAM_ASSIGNMENT NOT IN ('OK','NULL');
