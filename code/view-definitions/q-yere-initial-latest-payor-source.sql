/*
View Name: Q_YERE_INITIAL_LATEST_PAYOR_SOURCE
Category: View Definitions

See docs/view-definitions/q-yere-initial-latest-payor-source.md for full documentation.
*/

-- CREATE VIEW DBO.Q_YERE_INITIAL_LATEST_PAYOR_SOURCE AS
WITH [ALL_PAYOR] AS (
    SELECT
        EP.CLIENT_NUMBER,
        EP.TIEDENROLLMENT,
        EP.DOCSERNO,
        EP.PARENT_DOCSERNO,
        EP.FORM_TYPE,
        EP.PAYOR_SOURCE_START_DATE,
        EP.PAYOR_SOURCE_END_DATE,
        EP.PAYOR_SOURCE_DESCRIPTION,
        EP.MANAGED_MEDICAID_PROVIDER_DESCRIPTION,
        EP.SHOW_ME_HEALTHY_KIDS,
        EP.VISIT_DATE,
        EP.VISIT_TIME,
        EP.USERID
    FROM DBO.Q_YERE_ALL_PAYOR_SOURCE AS [EP]
),

[INITIAL_PAYOR] AS (
    SELECT
        CLIENT_NUMBER,
        TIEDENROLLMENT,
        DOCSERNO AS [INITIAL_DOCSERNO],
        PARENT_DOCSERNO AS [INITIAL_PARENT_DOCSERNO],
        FORM_TYPE AS [INITIAL_PARENT_FORM_TYPE],
        CAST(PAYOR_SOURCE_START_DATE AS DATE) AS [INITIAL_PAYOR_SOURCE_START_DATE],
        CAST(PAYOR_SOURCE_END_DATE AS DATE) AS [INITIAL_PAYOR_SOURCE_END_DATE],
        PAYOR_SOURCE_DESCRIPTION AS [INITIAL_PAYOR_SOURCE_DESCRIPTION],
		MANAGED_MEDICAID_PROVIDER_DESCRIPTION AS [INITIAL_MANAGED_MEDICAID_PROVIDER_DESCRIPTION],
        SHOW_ME_HEALTHY_KIDS AS [INITIAL_SHOW_ME_HEALTHY_KIDS],
        CAST(VISIT_DATE AS DATE) AS [INITIAL_VISIT_DATE],
        VISIT_TIME AS [INITIAL_VISIT_TIME],
        USERID AS [INITIAL_USERID]
    FROM (
        SELECT
            AP.*,
            ROW_NUMBER() OVER (
                PARTITION BY TIEDENROLLMENT
                ORDER BY PAYOR_SOURCE_START_DATE ASC, DOCSERNO ASC
            ) AS [RN]
        FROM ALL_PAYOR AS [AP]
    ) AS [X]
    WHERE RN = 1
),

[LATEST_PAYOR] AS (
    SELECT
        CLIENT_NUMBER,
        TIEDENROLLMENT,
        DOCSERNO AS [LATEST_DOCSERNO],
        PARENT_DOCSERNO AS [LATEST_PARENT_DOCSERNO],
        FORM_TYPE AS [LATEST_PARENT_FORM_TYPE],
        CAST(PAYOR_SOURCE_START_DATE AS DATE) AS [LATEST_PAYOR_SOURCE_START_DATE],
        CAST(PAYOR_SOURCE_END_DATE AS DATE) AS [LATEST_PAYOR_SOURCE_END_DATE],
        PAYOR_SOURCE_DESCRIPTION AS [LATEST_PAYOR_SOURCE_DESCRIPTION],
		MANAGED_MEDICAID_PROVIDER_DESCRIPTION AS [LATEST_MANAGED_MEDICAID_PROVIDER_DESCRIPTION],
        SHOW_ME_HEALTHY_KIDS AS [LATEST_SHOW_ME_HEALTHY_KIDS],
        CAST(VISIT_DATE AS DATE) AS [LATEST_VISIT_DATE],
        VISIT_TIME AS [LATEST_VISIT_TIME],
        USERID AS [LATEST_USERID]
    FROM (
        SELECT
            AP.*,
            ROW_NUMBER() OVER (
                PARTITION BY TIEDENROLLMENT
                ORDER BY PAYOR_SOURCE_START_DATE DESC, DOCSERNO DESC
            ) AS [RN]
        FROM ALL_PAYOR AS [AP]
    ) AS [X]
    WHERE RN = 1
)

SELECT
    L.CLIENT_NUMBER,
    L.TIEDENROLLMENT,

    -- Initial payor source
    I.INITIAL_DOCSERNO,
    I.INITIAL_PARENT_DOCSERNO,
    I.INITIAL_PARENT_FORM_TYPE,
    I.INITIAL_PAYOR_SOURCE_START_DATE,
    I.INITIAL_PAYOR_SOURCE_END_DATE,
    I.INITIAL_PAYOR_SOURCE_DESCRIPTION,
    I.INITIAL_MANAGED_MEDICAID_PROVIDER_DESCRIPTION,
    I.INITIAL_SHOW_ME_HEALTHY_KIDS,
    I.INITIAL_VISIT_DATE,
    I.INITIAL_VISIT_TIME,
    I.INITIAL_USERID,

    -- Latest payor source
    L.LATEST_DOCSERNO,
    L.LATEST_PARENT_DOCSERNO,
    L.LATEST_PARENT_FORM_TYPE,
    L.LATEST_PAYOR_SOURCE_START_DATE,
    L.LATEST_PAYOR_SOURCE_END_DATE,
    L.LATEST_PAYOR_SOURCE_DESCRIPTION,
    L.LATEST_MANAGED_MEDICAID_PROVIDER_DESCRIPTION,
    L.LATEST_SHOW_ME_HEALTHY_KIDS,
    L.LATEST_VISIT_DATE,
    L.LATEST_VISIT_TIME,
    L.LATEST_USERID,

	-- Status change flag
    CASE
        WHEN I.INITIAL_PAYOR_SOURCE_DESCRIPTION = L.LATEST_PAYOR_SOURCE_DESCRIPTION
        THEN 0
        ELSE 1
    END AS [STATUS_CHANGED_FLAG]

FROM LATEST_PAYOR AS [L]
LEFT JOIN INITIAL_PAYOR AS [I]
    ON I.TIEDENROLLMENT = L.TIEDENROLLMENT
INNER JOIN DBO.Q_CLIENT_BHN AS [C]
    ON C.CLIENT_NUMBER = L.CLIENT_NUMBER;
