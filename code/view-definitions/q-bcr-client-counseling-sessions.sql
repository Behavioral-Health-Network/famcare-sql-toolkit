USE BEHAVHEALT_LIVE;
GO

SELECT BCC.ID,
	BCC.DOCSERNO,
	BCC.TIEDENROLLMENT,
	CAST(BCC.VISITDT AS DATE) AS [VISITDT],
	BCC.VISITTM,
	BCC.USERID,
	C.CLIENT_NUMBER,
	CAST(BCC.PATHWAY_DATE AS DATE) AS [PATHWAY_DATE],
	CAST(BCC.SESSION_DATE AS DATE) AS [SESSION_DATE],
	BCC.SESSION_FORMAT,
	BCC.SESSION_GRANT,
	BCC.COUNSELING_AGENCY AS [COUNSELING_AGENCY_CODE],
	BCA.DESCRIPTION AS [COUNSELING_AGENCY_DESCRIPTION]
FROM DBO.PWBCRCLIENTCOUNSELINGSESSIONS AS [BCC]
INNER JOIN DBO.Q_CLIENT_BHN AS [C]
	ON C.CLIENT_NUMBER = BCC.CLIENTNUMBER
LEFT JOIN DBO.BCR_GRANT AS [GRANT]
	ON BCC.SESSION_GRANT = [GRANT].CODE
LEFT JOIN DBO.BCR_COUNSELING_AGENCIES AS [BCA]
	ON BCC.COUNSELING_AGENCY = BCA.CODE
WHERE BCC.DOCREVNO = ' 0 ';