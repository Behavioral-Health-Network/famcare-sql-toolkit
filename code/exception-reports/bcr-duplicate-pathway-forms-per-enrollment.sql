SELECT BENROLL.CLIENT_NUMBER,
	BENROLL.PWY_START_DATE,
	BENROLL.PWY_EVENT,
	BENROLL.EVENT_START_DATE,
	BENROLL.PEC_PATHCLIENT_DOCSERNO,
	COUNT(BENROLL.PWY_FORMS_DOCSERNO) AS [COUNT PWY FORM]
FROM BEHAVHEALT_LIVE.DBO.Q_BCR_PATHCLIENT_ENROLLMENTS AS [BENROLL]
WHERE BENROLL.PE_DATE_ACCOMPLISHED IS NOT NULL
GROUP BY BENROLL.CLIENT_NUMBER,
	BENROLL.PWY_START_DATE,
	BENROLL.PWY_EVENT,
	BENROLL.EVENT_START_DATE,
	BENROLL.PEC_PATHCLIENT_DOCSERNO
HAVING COUNT(BENROLL.PWY_FORMS_DOCSERNO) > 1;
