INTO DBO.ERE_BULK_UPDATE_PRIMARYPROVIDERCODE
FROM (SELECT
   PP.CLIENTNUMBER,
   PP.DOCSERNO,
   PP.STARTINGDATE, 
   PP.ENDINGDATE, -- use this date to update PPCH.ENDINGDATE
   PP.CLOSINGREASON,
   PP.BULK_DISMISSAL_SOURCE,
   PPCH.PARENTDOCSERNO,
   PPCH.ID,
   PPCH.VISITDT,     --Update this date
   PPCH.VISITTM,     --Update this time
   PPCH.USERID,      --Update this userid
   PPCH.PRIMARYPROVIDERCODE, 
   PPCH.STARTINGDATE AS [PPCH_STARTINGDATE], 
   PPCH.ENDINGDATE AS [PPCH_ENDINGDATE]   --Update this date
FROM DBO.PRIMARYPROVIDERCODEHISTORY AS [PPCH]
   INNER JOIN (SELECT CLIENTNUMBER, 
                PARENTDOCSERNO, 
                MAX(ID) AS [ID] 
              FROM DBO.PRIMARYPROVIDERCODEHISTORY 
              WHERE DOCREVNO = ' 0 ' 
              GROUP BY CLIENTNUMBER, 
                      PARENTDOCSERNO
       ) AS [LATEST]
