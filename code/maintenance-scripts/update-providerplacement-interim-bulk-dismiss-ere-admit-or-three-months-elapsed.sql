        ON W.CLIENT_NUMBER = PP.CLIENTNUMBER
       AND W.DOCSERNO = PP.DOCSERNO
    WHERE PP.ENDINGDATE IS NULL
      AND PP.DOCREVNO = ' 0 '
      AND PP.PATHWAY = 55320250326123001961;

