----- BULK UPDATE USERCASELOAD -----

/*
Performs an update to the `enddate` in the `USERCASELOAD` table to remove
dismissed clients from program workers' caseloads. As noted in the
`PLACEMENTPROGRAMWORKERHISTORY` update, this is a necessary separate step
because ending program worker assignment to an enrollment there does not impact
the caseload.
 */

-- create working table
SELECT *
INTO DBO.ERE_BULK_UPDATE_USERCASELOAD
FROM (SELECT 
   PP.CLIENTNUMBER,
   PP.DOCSERNO,
   PP.STARTINGDATE, 
   PP.ENDINGDATE, -- strip the time and use this date to update U.ENDDATE
   PP.CLOSINGREASON,
   PP.BULK_DISMISSAL_SOURCE,
   U.ID,
   U.USERID,      --Update this userid
   U.BEGINDATE, 
   U.BEGINTIME,
